CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

CREATE TABLE ledger_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT,
    code VARCHAR(64) NOT NULL,
    name VARCHAR(160) NOT NULL,
    account_type VARCHAR(16) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    is_system BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ledger_account_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT ck_ledger_account_type CHECK
        (account_type IN ('ASSET', 'LIABILITY', 'EQUITY', 'INCOME', 'EXPENSE')),
    CONSTRAINT ck_ledger_account_currency CHECK (currency_code = UPPER(currency_code)),
    CONSTRAINT ck_ledger_account_owner CHECK
        ((is_system = TRUE AND owner_id IS NULL) OR (is_system = FALSE AND owner_id IS NOT NULL)),
    CONSTRAINT uq_ledger_account_code_per_owner UNIQUE (owner_id, code),
    CONSTRAINT uq_ledger_account_id_owner_currency UNIQUE (id, owner_id, currency_code),
    CONSTRAINT uq_ledger_account_id_currency UNIQUE (id, currency_code)
);

CREATE TABLE financial_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    ledger_account_id BIGINT NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    account_type VARCHAR(24) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_financial_account_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_financial_account_ledger FOREIGN KEY (ledger_account_id, owner_id, currency_code)
        REFERENCES ledger_account (id, owner_id, currency_code) ON DELETE RESTRICT,
    CONSTRAINT uq_financial_account_ledger UNIQUE (ledger_account_id),
    CONSTRAINT ck_financial_account_type CHECK
        (account_type IN ('BANK', 'WALLET', 'CASH')),
    CONSTRAINT ck_financial_account_currency CHECK (currency_code = UPPER(currency_code))
);

CREATE INDEX ix_financial_account_owner ON financial_account (owner_id, id);
CREATE INDEX ix_ledger_account_owner ON ledger_account (owner_id, id);

CREATE TABLE category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_category_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT uq_category_name_per_owner UNIQUE (owner_id, name),
    CONSTRAINT uq_category_id_owner UNIQUE (id, owner_id)
);

CREATE TABLE journal_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    category_id BIGINT,
    reversal_of_transaction_id BIGINT,
    description VARCHAR(500) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    posted_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_journal_transaction_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_journal_transaction_category FOREIGN KEY (category_id, owner_id)
        REFERENCES category (id, owner_id) ON DELETE RESTRICT,
    CONSTRAINT fk_journal_transaction_reversal FOREIGN KEY (reversal_of_transaction_id)
        REFERENCES journal_transaction (id) ON DELETE RESTRICT,
    CONSTRAINT uq_journal_transaction_reversal UNIQUE (reversal_of_transaction_id),
    CONSTRAINT ck_journal_transaction_status CHECK (status IN ('DRAFT', 'POSTED', 'REVERSED')),
    CONSTRAINT ck_journal_transaction_not_self_reversal CHECK
        (reversal_of_transaction_id IS NULL OR reversal_of_transaction_id <> id),
    CONSTRAINT ck_journal_transaction_posted_at CHECK
        ((status = 'DRAFT' AND posted_at IS NULL) OR (status <> 'DRAFT' AND posted_at IS NOT NULL)),
    CONSTRAINT uq_journal_transaction_id_owner UNIQUE (id, owner_id)
);

CREATE INDEX ix_journal_transaction_owner_time
    ON journal_transaction (owner_id, occurred_at DESC, id DESC);
CREATE INDEX ix_journal_transaction_category ON journal_transaction (category_id);

CREATE TABLE journal_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_transaction_id BIGINT NOT NULL,
    ledger_account_id BIGINT NOT NULL,
    currency_code CHAR(3) NOT NULL,
    debit_amount NUMERIC(19, 4) NOT NULL DEFAULT 0,
    credit_amount NUMERIC(19, 4) NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_journal_entry_transaction FOREIGN KEY (journal_transaction_id)
        REFERENCES journal_transaction (id) ON DELETE RESTRICT,
    CONSTRAINT fk_journal_entry_ledger_account_currency FOREIGN KEY (ledger_account_id, currency_code)
        REFERENCES ledger_account (id, currency_code) ON DELETE RESTRICT,
    CONSTRAINT ck_journal_entry_currency CHECK (currency_code = UPPER(currency_code)),
    CONSTRAINT ck_journal_entry_nonnegative CHECK (debit_amount >= 0 AND credit_amount >= 0),
    CONSTRAINT ck_journal_entry_exactly_one_side CHECK
        ((debit_amount > 0 AND credit_amount = 0) OR (credit_amount > 0 AND debit_amount = 0))
);

CREATE INDEX ix_journal_entry_transaction ON journal_entry (journal_transaction_id, id);
CREATE INDEX ix_journal_entry_ledger_account ON journal_entry (ledger_account_id, journal_transaction_id);

CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    journal_transaction_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_idempotency_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_idempotency_transaction_owner FOREIGN KEY (journal_transaction_id, owner_id)
        REFERENCES journal_transaction (id, owner_id) ON DELETE RESTRICT,
    CONSTRAINT uq_idempotency_owner_key UNIQUE (owner_id, idempotency_key),
    CONSTRAINT uq_idempotency_transaction UNIQUE (journal_transaction_id)
);

CREATE TABLE budget (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    currency_code CHAR(3) NOT NULL,
    amount NUMERIC(19, 4) NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_budget_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_budget_category_owner FOREIGN KEY (category_id, owner_id)
        REFERENCES category (id, owner_id) ON DELETE RESTRICT,
    CONSTRAINT ck_budget_currency CHECK (currency_code = UPPER(currency_code)),
    CONSTRAINT ck_budget_amount CHECK (amount > 0),
    CONSTRAINT ck_budget_period CHECK (period_end >= period_start),
    CONSTRAINT uq_budget_category_period UNIQUE (owner_id, category_id, period_start, period_end)
);

CREATE INDEX ix_budget_owner_period ON budget (owner_id, period_start, period_end);

CREATE TABLE audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_owner_id BIGINT,
    journal_transaction_id BIGINT,
    event_type VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id BIGINT NOT NULL,
    details VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_owner_id)
        REFERENCES app_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_audit_transaction FOREIGN KEY (journal_transaction_id)
        REFERENCES journal_transaction (id) ON DELETE RESTRICT
);

CREATE INDEX ix_audit_event_entity ON audit_event (entity_type, entity_id, created_at);
CREATE INDEX ix_audit_event_transaction ON audit_event (journal_transaction_id, created_at);
